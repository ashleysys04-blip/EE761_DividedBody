#!/usr/bin/env python3
"""Step 16: relaxation oscillation of each latch under a constant drain current (cf. Oscillation_basecode: I source + C on the drain).
Device = ideal metal-core sink SINK_TE8_XS60 (1010_sink, gate -0.2 V, Rtap 1e7 Ohm), loaded from its gate-bias .str.
A latch oscillates when I_trigger (off-branch current at V_on) < I_in < I_hold (on-branch current at V_off).
From 1010_sink/SINK_TE8_XS60.log_tr.log (0.7 V/ms sweep):
  loop 1 (right STL): V_on 1.50 V at 6e-11 A, V_off 1.09 V at 1.2e-8 A      -> 6e-11 < I < 1.2e-8
  loop 2 (left STL):  V_on 4.62 V at 3.5e-7 A, V_off 2.09 V at 1.0-1.3e-6 A -> 3.5e-7 < I < 1.0e-6
C is chosen so that I/C ~ 1-2 V/ms, close to the DC sweep rate (latch voltages comparable)."""
import os
H = os.path.dirname(os.path.abspath(__file__))
# name, I_in (A, injected into the drain), C (F), t_stop (s), snapshot times (s)
JOBS = [('OSC_R_1n',   1e-9, 1e-12, 5e-3,  [1e-3, 2e-3, 3e-3, 4e-3, 5e-3]),
        ('OSC_L_600n', 6e-7, 3e-10, 15e-3, [3e-3, 5e-3, 7e-3, 9e-3, 11e-3, 13e-3, 15e-3]),
        ('OSC_R_3n',   3e-9, 3e-12, 5e-3,  [2e-3, 5e-3]),
        ('OSC_L_800n', 8e-7, 4e-10, 15e-3, [5e-3, 10e-3, 15e-3]),
        # 2026-10-28, after OSC_L_600n settled at 2.08 V: left window re-read as ~3.6e-7 < I < ~5.5e-7 A (fire = 3.55 V / Rtap,
        # keep = 1.15 V / Rtap + left holding ~4.3e-7 A). OSC_R_30n tests the upper bound of the right loop: 30 nA is above the
        # right turn-off current (1.2e-8 A) but below the top of the right latch jump (~6e-8 A).
        ('OSC_L_450n', 4.5e-7, 2.25e-10, 15e-3, [3e-3, 5e-3, 7e-3, 9e-3, 11e-3, 13e-3, 15e-3]),
        ('OSC_R_30n',  3e-8, 3e-11, 5e-3, [1e-3, 2e-3, 3e-3, 4e-3, 5e-3])]
T = """# {n} : Step 16 oscillation, generated by 1028_osc/make_osc.py
# Constant current {i:g} A into the drain node with C = {c:g} F to ground (I/C = {r:.2f} V/ms). Gate -0.2 V DC, tap -> 1e7 Ohm -> GND.
# Device: ideal metal-core sink SINK_TE8_XS60 (structure + gate bias from 1010_sink/SINK_TE8_XS60_VG.str, copied here).
# Expected: {exp}

go atlas simflags="-P 1"
.begin
Idrain 1 0 pwl 0, 0, 1e-6, {ni:g}
Vgate  2 0 -0.2
Rtap   3 0 1e7
Cdrain 1 0 {c:g}
Adev 1=drain 0=source 2=gate 3=tap 0=substrate width=0.5 infile=SINK_TE8_XS60_VG.str
.nodeset v(1)=0 v(2)=-0.2 v(3)=0
.numeric lte=0.3 toltr=1e-5
.options print relpot
.log outfile={n}.log
.tran 1e-9 {t:g}
.save master={n}_T tsave={ts}
.end

material material=silicon taun0=1e-8 taup0=1e-8
models print bgn consrh conmob fldmob fermi trap.tunnel bbt.std temp=300
impact selb length.rel
output band.param con.band val.band recomb u.srh u.bbt qtunn.bbt impact e.field traps
method newton climit=100 itlimit=200 trap maxtraps=10

go atlas simflags="-P 1"
quit
"""
EXP = {'R': 'loop 1 only: drain node saw-tooth between ~1.09 and ~1.50 V (right STL fires and resets); left STL stays off',
       'R30': 'holding-current criterion: right STL fires at 1.50 V and stays on (no saw-tooth); jump-span criterion: saw-tooth',
       'L': 'right STL latches on the way up and stays on; drain node saw-tooth between ~2.09 and ~4.62 V (left STL fires and resets)'}
for n, i, c, t, ts in JOBS:
    if os.path.exists(os.path.join(H, n + '.in')): continue   # never rewrite a deck that already exists
    open(os.path.join(H, n + '.in'), 'w').write(T.format(n=n, i=i, ni=-i, c=c, r=i / c * 1e-3, t=t, ts=' '.join('%g' % x for x in ts), exp=EXP['R30' if n == 'OSC_R_30n' else n[4]]))
    print(n)
