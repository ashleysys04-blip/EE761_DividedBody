#!/usr/bin/env python3
"""Step 16b: standalone LEFT STL of the current main device (SINK_TE8_XS60 geometry, DD, Si tau 1e-8 s, gate -0.2 V),
to read the left STL's own trigger current I_off,L (off branch at V_on) and holding current I_h,L (current at the
steepest turn-off on the way down) vs left body doping. A left-loop oscillation under current drive needs I_h,L > I_off,L.
Built from 1010_sink/SINK_TE8_XS60.in: right body -> n+ 1e20 (island + right side = drain of this STL), no tap electrode.
Drain: MixedMode voltage ramp 0 -> 6 -> 0 V at 0.7 V/ms (same as the main DC sweep). A voltage sweep is used instead of a
current ramp: it follows the on branch down to its turn-off point and cannot fall into a fast self-oscillation."""
import os, re
H = os.path.dirname(os.path.abspath(__file__)); SRC = os.path.join(H, '..', '1010_sink', 'SINK_TE8_XS60.in')
src = open(SRC).read()
dev = src[src.index('go atlas'):src.index('go atlas', src.index('go atlas') + 1)]
tail = src[src.index('.end') + 4:]
for nl in ('6e17', '7e17', '8e17'):
    n = 'LSTL_P' + nl
    d = dev.replace('doping uniform conc=6.0e17 p.type x.min=$Lsd x.max=$XiL', 'doping uniform conc=%s p.type x.min=$Lsd x.max=$XiL' % nl.replace('e', '.0e'))
    d = d.replace('doping uniform conc=7.0e17 p.type x.min=$XiR x.max=$Lsd+$Lg', 'doping uniform conc=1e20 n.type x.min=$XiR x.max=$Lsd+$Lg')
    d = re.sub(r'electrode name=tap[^\n]*\n', '', d)
    d = d.replace('SINK_TE8_XS60', n)
    assert ('conc=%s p.type' % nl.replace('e', '.0e')) in d and 'name=tap' not in d and 'conc=7.0e17 p.type x.min=$XiR' not in d
    hdr = ('# %s : Step 16b standalone left STL, left body %s, generated by 1028_leftstl/make_leftstl.py from 1010_sink/SINK_TE8_XS60.in\n'
           '# Right body -> n+ drain, no tap. DD, tau 1e-8 s, gate -0.2 V. Drain 0 -> 6 -> 0 V at 0.7 V/ms.\n\n') % (n, nl)
    mm = ('go atlas simflags="-P 1"\n.begin\nVdrain 1 0 pwl 0, 0, 8.571429e-03, 6.0, 1.714286e-02, 0\nVgate  2 0 -0.2\n'
          'Adev 1=drain 0=source 2=gate 0=substrate width=0.5 infile=%s_VG.str\n.nodeset v(1)=0 v(2)=-0.2\n'
          '.numeric lte=0.3 toltr=1e-5\n.options print relpot\n.log outfile=%s.log\n.tran 1e-9 1.714286e-02\n.end\n') % (n, n)
    open(os.path.join(H, n + '.in'), 'w').write(hdr + d + mm + tail)
    print(n)
