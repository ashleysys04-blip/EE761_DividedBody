#!/usr/bin/env python3
"""Island-width sweep at fixed island lifetime: the coupling knob as a geometry (L_p / W_island) instead of a lifetime.

Base: 1010_sink/NOKILL_TE8_XS60.in (island tau = Si tau = 1e-8 s, island 30 nm, coupled: 2nd latch 1.968 V).
Both bodies keep their length (left 165 nm, right 105 nm), only the n+ island between them gets wider, so the gate
length becomes Lg = 0.27 um + W_island. Drain-side mesh lines move with the drain edge. Probes follow the island.
Island hole diffusion length at tau0 = 1e-8 s is about 32 nm (consrh in 1e20 n+, from the island-lifetime sweep), so
W = 15 ... 200 nm spans L/W = 2.1 ... 0.16; the lifetime sweep put the decoupling between L/W 0.33 and 0.1.
ISLW120_KILL: 120 nm island with the island lifetime killed (1e-12 s, as DDS_TE8_XS60) = decoupled reference at that width,
separates the coupling effect from the longer gate (Lg grows with W). Replaced ISLW200_KILL on 11/2 (200 nm is outside
the useful knob range 15-120 nm; ISLW200_KILL.in is kept but not run).
Existing decks are not rewritten."""
import os
H = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(H, '..', '1010_sink', 'NOKILL_TE8_XS60.in')
src = open(BASE).read()
KILL = 'material region=10 taun0=1e-12 taup0=1e-12\nmaterial region=9 taun0=1e-12 taup0=1e-12\n'
REP = [('set Lg = 0.3\n', None),
       ('set Xsplit = $Lsd+$Lg*0.60\n', None),   # -> $Lsd + 0.165 + W/2 as a number (Wisl is set after Xsplit)
       ('set Wisl = 0.03\n', None),
       ('x.mesh loc=0.760 spac=0.003', 'x.mesh loc=$Lsd+$Lg-0.04 spac=0.003'),
       ('x.mesh loc=0.785 spac=0.001', 'x.mesh loc=$Lsd+$Lg-0.015 spac=0.001'),
       ('x.mesh loc=0.815 spac=0.003', 'x.mesh loc=$Lsd+$Lg+0.015 spac=0.003'),
       ('probe name=VB_right potential x=0.7325', 'probe name=VB_right potential x=$XiR+0.0375'),
       ('probe name=V_island potential x=0.65', 'probe name=V_island potential x=$Xsplit'),
       ('probe name=V_neck   potential x=0.65', 'probe name=V_neck   potential x=$Xsplit')]
assert all(src.count(o) == 1 for o, _ in REP), 'base deck changed'
POST = 'taup0=$tp\nmodels print'          # material line after .end (the device-section one is followed by the kill comment)
assert src.count(POST) == 1 and src.count('# lifetime killing in the island and its tap neck\n') == 1
JOBS = [(w, False) for w in (0.06, 0.12, 0.2, 0.015, 0.09, 0.045)] + [(0.12, True)]
for w, kill in JOBS:
    n = 'ISLW%03d%s' % (round(w * 1000), '_KILL' if kill else '')
    fn = os.path.join(H, n + '.in')
    if os.path.exists(fn):
        print('exists, not rewritten:', n); continue
    d = src
    for o, r in REP:
        d = d.replace(o, r if r else o.replace('0.3\n', '%g\n' % round(0.27 + w, 4)).replace('0.03\n', '%g\n' % w)
                      .replace('$Lg*0.60', '0.165+%g' % round(w / 2, 4)))
    if kill:
        d = d.replace('# lifetime killing in the island and its tap neck\n', '# lifetime killing in the island and its tap neck\n' + KILL)
        d = d.replace(POST, 'taup0=$tp\n' + KILL + 'models print')
    d = d.replace('NOKILL_TE8_XS60', n)
    hdr = (f'# {n} : island-width sweep, generated by 1030_islw/make_islw.py from 1010_sink/NOKILL_TE8_XS60.in\n'
           f'# Changes: island width 30 -> {w * 1000:g} nm with both body lengths kept (Lg = 0.27 um + W), drain mesh and probes moved'
           + (', island + neck lifetime killed (1e-12 s).\n' if kill else '. Island lifetime not killed (Si tau 1e-8 s).\n'))
    open(fn, 'w').write(hdr + d); print('wrote', n + '.in')
