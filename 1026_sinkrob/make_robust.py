#!/usr/bin/env python3
"""Step 15: robustness of the metal-core sink (reviewer question: "are the two latches an artefact of an ideal
ohmic boundary and of 10 nm / 10 nm / 10 nm geometry?").  Base design: 1007_ddsplit/DDS_TE8_XS60.in
(island centre at 60 % of L_G, tau0_Si = 1e-8 s, R_tap = 10 MOhm), island lifetime NOT killed.
Parameters
  WISL : island width (um)          SHL/SHR : n+ Si left/right of the core (um) -> core = WISL - SHL - SHR
  RES  : Si left under the core (um, hole bypass under an incomplete trench)
  SR   : finite surface recombination velocity at the core (cm/s, both carriers); None = ideal ohmic (equilibrium)
  CTAP : capacitance tap node -> ground (F), measurement / pad parasitic
  GAP  : 0 = one continuous gate (core buried under it, tap taken out below / sideways);
         > 0 = two gates with a gap (um) over the island, tied to the same V_G, core contacted from the top through the gap
Probes are placed at the body centres and inside the left n+ shell (the old V_island probe sat in the left body)."""
import os, re
SRC = '/home/ysseo/novel/1007_ddsplit/DDS_TE8_XS60.in'
B = dict(WISL=0.03, SHL=0.01, SHR=0.01, RES=0.0, SR=None, CTAP=0.0, GAP=0.0)
CASES = [
    ('ROB_W60',     dict(WISL=0.06)),
    ('ROB_W100',    dict(WISL=0.10)),
    ('ROB_OFFP5',   dict(SHL=0.015, SHR=0.005)),
    ('ROB_OFFM5',   dict(SHL=0.005, SHR=0.015)),
    ('ROB_RES5',    dict(RES=0.005)),
    ('ROB_RES15',   dict(RES=0.015)),
    ('ROB_SR1e6',   dict(SR=1e6)),
    ('ROB_SR1e4',   dict(SR=1e4)),
    ('ROB_SR1e2',   dict(SR=1e2)),
    ('ROB_C10p',    dict(CTAP=10e-12)),
    ('ROB_C100p',   dict(CTAP=100e-12)),
    ('ROB_SG_W60',  dict(WISL=0.06, GAP=0.06)),
    ('ROB_SG_W100', dict(WISL=0.10, GAP=0.08)),
]

def deck(name, p):
    s = open(SRC).read()
    s = s.replace('DDS_TE8_XS60_', name + '_').replace('DDS_TE8_XS60.log', name + '.log')
    s = re.sub(r'^#.*\n', '', s, flags=re.M)                     # drop the inherited (stale) header comments
    core = p['WISL'] - p['SHL'] - p['SHR']; assert core > 0.004, name
    hdr = [f'# {name} : Step 15 sink robustness, generated by 1026_sinkrob/make_robust.py from 1007_ddsplit/DDS_TE8_XS60.in',
           '# ' + ', '.join(f'{k}={v}' for k, v in p.items()) + f'  (core width {core*1000:.0f} nm)',
           '# Island: n+ 1e20, normal Si lifetime (NOT killed). Metal core = tap electrode inside the island; no BOX neck.',
           '# Gate: ' + ('one continuous gate over both bodies and the island.' if p['GAP'] == 0 else
                        f'two gates (gap {p["GAP"]*1000:.0f} nm over the island) (left gate, right rgate) tied to V_G; core reaches the top through the gap (oxide-filled).')]
    s = '\n'.join(hdr) + '\n' + s
    s = s.replace('set Wisl = 0.03', f'set Wisl = {p["WISL"]}')
    s = s.replace('material region=10 taun0=1e-12 taup0=1e-12\n', '').replace('material region=9 taun0=1e-12 taup0=1e-12\n', '')
    s = s.replace('region num=9 x.min=$XiL x.max=$XiR y.min=$tsi y.max=$Ybot silicon\n', '')
    s = s.replace('doping uniform conc=1e20 n.type reg=9\n', '')
    s = s.replace('region num=10 x.min=$XiL x.max=$XiR y.min=0 y.max=$tsi silicon\n', 'region num=9 x.min=$XiL x.max=$XiR y.min=0 y.max=$tsi silicon\n')
    ytop = '0' if p['GAP'] == 0 else '-$tox-$tgate'
    s = s.replace('electrode name=tap x.min=$XiL x.max=$XiR y.min=$Ybot y.max=$Ybot',
                  f'set XcL = $XiL+{p["SHL"]}\nset XcR = $XiR-{p["SHR"]}\n'
                  f'electrode name=tap x.min=$XcL x.max=$XcR y.min={ytop} y.max=$tsi-{p["RES"]}')
    s = s.replace('x.mesh loc=$XiR spac=0.003\n', f'x.mesh loc=$XcL spac=0.001\nx.mesh loc=$XcR spac=0.001\nx.mesh loc=$XiR spac=0.003\n')
    s = s.replace('x.mesh loc=$XiL spac=0.003\n', f'set XcL = $XiL+{p["SHL"]}\nset XcR = $XiR-{p["SHR"]}\nx.mesh loc=$XiL spac=0.003\n', 1)
    if p['RES'] > 0:
        s = s.replace('y.mesh loc=$tsi spac=0.005\n', f'y.mesh loc=$tsi-{p["RES"]} spac=0.001\ny.mesh loc=$tsi spac=0.002\n')
    # probes: body centres, left shell
    s = re.sub(r'probe name=VB_left .*\n', 'probe name=VB_left  potential x=($Lsd+$XiL)/2 y=0.035\n', s)
    s = re.sub(r'probe name=VB_right .*\n', 'probe name=VB_right potential x=($XiR+$Lsd+$Lg)/2 y=0.035\n', s)
    s = re.sub(r'probe name=V_island .*\n', 'probe name=V_shellL potential x=$XiL+0.002 y=0.025\n', s)
    s = re.sub(r'probe name=V_neck .*\n', '', s)
    s = re.sub(r'probe name=PH_left .*\n', 'probe name=PH_left  P.CONC x=($Lsd+$XiL)/2 y=0.035\n', s)
    s = re.sub(r'probe name=PH_right .*\n', 'probe name=PH_right P.CONC x=($XiR+$Lsd+$Lg)/2 y=0.035\n', s)
    if p['GAP'] > 0:
        g = p['GAP']
        s = s.replace('region num=1 x.min=$Lsd x.max=$Lsd+$Lg y.max=-$tox poly\n',
                      f'region num=1 x.min=$Lsd x.max=$Xsplit-{g/2} y.max=-$tox poly\n')
        s = s.replace('region num=9 x.min=$XiL x.max=$XiR y.min=0 y.max=$tsi silicon\n',
                      'region num=9 x.min=$XiL x.max=$XiR y.min=0 y.max=$tsi silicon\n'
                      f'region num=10 x.min=$Xsplit+{g/2} x.max=$Lsd+$Lg y.max=-$tox poly\n'
                      f'region num=11 x.min=$Xsplit-{g/2} x.max=$Xsplit+{g/2} y.min=-$tox-$tgate y.max=-$tox oxide\n')
        s = s.replace('electrode name=gate x.min=$Lsd x.max=$Lsd+$Lg y.min=-$tox y.max=-$tox\n',
                      f'electrode name=gate x.min=$Lsd x.max=$Xsplit-{g/2} y.min=-$tox y.max=-$tox\n'
                      f'electrode name=rgate x.min=$Xsplit+{g/2} x.max=$Lsd+$Lg y.min=-$tox y.max=-$tox\n')
        s = s.replace('doping uniform conc=1e21 n.type reg=1\n', 'doping uniform conc=1e21 n.type reg=1\ndoping uniform conc=1e21 n.type reg=10\n')
        s = s.replace('solve vfinal=-0.2 vstep=-0.05 name=gate\n',
                      'solve vfinal=-0.2 vstep=-0.05 name=gate\nsolve vfinal=-0.2 vstep=-0.05 name=rgate\n')
        s = s.replace('Adev 1=drain 0=source 2=gate 3=tap', 'Adev 1=drain 0=source 2=gate 2=rgate 3=tap')
    if p['SR'] is not None:
        c = f'contact name=tap workfun=4.17 surf.rec vsurfn={p["SR"]:g} vsurfp={p["SR"]:g}\n'
        s = s.replace('contact name=substrate\n', 'contact name=substrate\n' + c, 1)
        s = s.replace('.end\n', '.end\n' + c, 1)
    if p['CTAP'] > 0:
        s = s.replace('Rtap   3 0 1e7\n', f'Rtap   3 0 1e7\nCtap   3 0 {p["CTAP"]:g}\n')
    assert 'region num=10 x.min=$XiL' not in s and 'XcL' in s
    return s

if __name__ == '__main__':
    for name, ch in CASES:
        p = dict(B); p.update(ch)
        if os.path.exists(name + '.in'): continue
        open(name + '.in', 'w').write(deck(name, p)); print('wrote', name)
