#!/usr/bin/env python3
"""Third jump (hole loop) of the coupled device: TCAD checks of the body hole-balance prediction (1103_model/third_latch.py).

  ISLW035, ISLW040  island width 35 / 40 nm, island tau = Si tau 1e-8 s (as 1030_islw/make_islw.py): the model puts the
                    onset of the third jump between 30 nm (present) and 45 nm (absent) via exp(-W / L_eff(I)) * eta0 * beta ~ 0.85
  T3_W030_DENSE     1010_sink/NOKILL_TE8_XS60 with extra snapshots at 3.25-3.55 V up and down (around the 3.38 V jump)
  T3_W030_HEAT      the same device with lattice heating (models lat.temp, thermal contact at the substrate bottom, 300 K):
                    does the third jump survive self-heating at ~6 mA/um?
Existing decks are not rewritten."""
import os, runpy, re
H = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(H, '..')
I = runpy.run_path(os.path.join(R, '1030_islw', 'make_islw.py'))           # base deck text and replacement rules of the width sweep
src, REP = I['src'], I['REP']
RATE = 700.0


def write(n, d, hdr):
    fn = os.path.join(H, n + '.in')
    if os.path.exists(fn): print('exists, not rewritten:', n); return
    open(fn, 'w').write(hdr + d); print('wrote', n)


for w in (0.035, 0.04):
    n = 'ISLW%03d' % round(w * 1000); d = src
    for o, r in REP:
        d = d.replace(o, r if r else o.replace('0.3\n', '%g\n' % round(0.27 + w, 4)).replace('0.03\n', '%g\n' % w)
                      .replace('$Lg*0.60', '0.165+%g' % round(w / 2, 4)))
    d = d.replace('NOKILL_TE8_XS60', n)
    write(n, d, f'# {n} : island-width sweep point for the third-jump onset, generated by 1103_third/make_third.py '
                f'(rules of 1030_islw/make_islw.py) from 1010_sink/NOKILL_TE8_XS60.in. Island lifetime not killed.\n')

base = open(os.path.join(R, '1010_sink', 'NOKILL_TE8_XS60.in')).read()
ts = re.search(r'tsave=([^\n]+)\n', base).group(1)
extra = [v / RATE for v in (3.25, 3.30, 3.35, 3.375, 3.40, 3.45, 3.55)] + [(12.0 - v) / RATE for v in (3.55, 3.45, 3.40, 3.375, 3.35, 3.30, 3.25)]
new = ' '.join('%.6e' % t for t in sorted(set([float(x) for x in ts.split()] + extra)))
d = base.replace('tsave=' + ts, 'tsave=' + new).replace('NOKILL_TE8_XS60', 'T3_W030_DENSE')
write('T3_W030_DENSE', d, '# T3_W030_DENSE : NOKILL_TE8_XS60 with extra snapshots 3.25-3.55 V up/down (make_third.py). '
      'Snapshot N follows the sorted tsave list.\n')

MOD = 'models print bgn consrh conmob fldmob fermi trap.tunnel bbt.std temp=$LT'
assert base.count(MOD) == 2 and base.count('contact name=substrate\n') == 1
d = base.replace(MOD, MOD + ' lat.temp').replace('contact name=substrate\n',
        'contact name=substrate\nthermcontact num=1 x.min=0 x.max=$Lsd+$Lg+$Lsd y.min=$Ybot y.max=$Ybot ext.temp=300\n')
d = d.replace('NOKILL_TE8_XS60', 'T3_W030_HEAT')
write('T3_W030_HEAT', d, '# T3_W030_HEAT : NOKILL_TE8_XS60 with lattice heating (models lat.temp, thermcontact at the substrate '
      'bottom y = $Ybot, 300 K), make_third.py.\n')
