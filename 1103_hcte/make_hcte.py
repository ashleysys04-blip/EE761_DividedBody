#!/usr/bin/env python3
"""Energy-balance (hcte) check of the coupled devices: does the second latch survive outside drift-diffusion?

Full-device hcte runs of the decoupled device stopped at 3.6-5.3 V (electron-temperature runaway at the right drain
junction, README Step 11), below its second latch (DD 4.78 V). The coupled devices latch the second time at 1.97-3.34 V
(DD), below that limit, so hcte can reach them. Bases (unchanged otherwise, DD runs in README Steps 17-19):
  HC_W030      1010_sink/NOKILL_TE8_XS60   coupled, island 30 nm  (DD 2nd latch 1.969 / off 1.956 V)
  HC_W060      1030_islw/ISLW060           coupled, 60 nm         (DD 2.193 / 2.019 V)
  HC_W120      1030_islw/ISLW120           coupled, 120 nm        (DD 3.339 / 2.040 V)
  HC_W120_KILL 1030_islw/ISLW120_KILL      island killed, 120 nm  (DD 4.761 / 2.577 V)
Changes vs base: hcte in both models lines, block Newton (as 1001/tap/MM_..._MF_HC_VGm0p2.in), and the drain ramp:
coupled decks 0 -> 4 -> 0 V (above every DD 2nd latch, so the down sweep is reached before a possible hcte stop),
killed deck 0 -> 6 -> 0 V (as the DD run). Same 0.7 V/ms. Existing decks are not rewritten."""
import os, re
H = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(H, '..')
JOBS = [('HC_W030', '1010_sink/NOKILL_TE8_XS60', 4.0), ('HC_W120', '1030_islw/ISLW120', 4.0),
        ('HC_W060', '1030_islw/ISLW060', 4.0), ('HC_W120_KILL', '1030_islw/ISLW120_KILL', 6.0)]
RATE = 700.0                                     # V/s
MOD = 'models print bgn consrh conmob fldmob fermi trap.tunnel bbt.std temp=$LT'
MET = 'method newton climit=100 itlimit=200 trap maxtraps=10'
for name, base, vmax in JOBS:
    fn = os.path.join(H, name + '.in')
    if os.path.exists(fn):
        print('exists, not rewritten:', name); continue
    src = open(os.path.join(R, base + '.in')).read(); b = os.path.basename(base)
    assert src.count(MOD) == 2 and src.count(MET) == 2, base
    pwl = re.search(r'Vdrain 1 0 pwl 0, 0, ([0-9.e+-]+), 6.0, ([0-9.e+-]+), 0\n', src); assert pwl, base
    tsv = re.search(r'tsave=([^\n]+)\n', src); tran = '.tran 1e-9 %s\n' % pwl.group(2); assert src.count(tran) == 1
    tp, te = vmax / RATE, 2 * vmax / RATE
    up = [v for v in (1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 5.0, 6.0) if v <= vmax]
    dn = [v for v in (5.0, 4.0, 3.5, 3.0, 2.5, 2.0, 1.5, 1.0, 0.0) if v < vmax]
    ts = ['%.6e' % (v / RATE) for v in up] + ['%.6e' % ((2 * vmax - v) / RATE) for v in dn]
    d = src.replace(MOD, MOD.replace('bgn ', 'bgn hcte ')).replace(MET, 'method block newton climit=100 itlimit=200 NBLOCKIT=200 trap maxtraps=10')
    d = d.replace(pwl.group(0), 'Vdrain 1 0 pwl 0, 0, %.6e, %g, %.6e, 0\n' % (tp, vmax, te)).replace(tran, '.tran 1e-9 %.6e\n' % te)
    d = d.replace('tsave=' + tsv.group(1), 'tsave=' + ' '.join(ts))
    d = d.replace(b, name)
    head = ('# %s : hcte (energy balance) check, generated by 1103_hcte/make_hcte.py from %s.in\n'
            '# Changes: hcte + block Newton; drain 0 -> %g -> 0 V at 0.7 V/ms. Snapshots (%s_T_tr_N): up %s / down %s V\n'
            % (name, base, vmax, name, ', '.join('%g' % v for v in up), ', '.join('%g' % v for v in dn)))
    open(fn, 'w').write(head + d); print('wrote', name)
