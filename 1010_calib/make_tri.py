#!/usr/bin/env python3
"""Triristor calibration decks (paper item 1): reproduce the measured double latch of
Noh et al., IEEE EDL 46(8) 2025 (bulk n-MOSFET, L_G 3 um, floating body) with our model set.
Doping from the paper's process flow and SIMS (Fig. 1e):
  p-well  : Gaussian, peak 5e16 at 0.10 um, char 0.19 um  (SIMS: ~5e16 to 150 nm, ~2e16 at 300 nm)
  S/D As  : Gaussian, 7e20 at surface, char 0.055 um       (SIMS: 1e19 at ~100 nm, 1e17 at ~160 nm)
  background p: NBG (wafer, not given; SIMS floor < 1e16)
Body is floating (no substrate contact), as in the measurement. Drain: MixedMode transient, Vdrain pwl 0 -> VMAX -> 0 V
at RATE V/ms, A-device width = W (the mesh width is ignored in MixedMode). Id-Vg: MixedMode .dc.
Targets: calib_targets.dat."""
import os
BASE = dict(W=600.0, VG=0.40, NBG=1e15, DSUB=5.0, TAU=1e-7, AUG=0, AN=1.0, BN=1.0, VMAX=13.0, RATE=0.7, IDVG=0, DPHI=0.0, RC=0.0, CIRC_R=0)
# Calibration stage 1 (2026-10-12): V_th and on-current from Id-Vg (device-only DC, IDVG=2).
#   DPHI: gate work-function shift vs n+ poly (4.17 eV) = flat-band correction (oxide charge / poly depletion unknown)
#   RC  : series resistance per S/D contact in Ohm (measured R_on ~143 Ohm at V_G 4 V, V_D 0.05 V; probe + contact + metal)
CASES = [
    ('TRI_IDVG',            dict(IDVG=1)),
    ('TRI_DEF_VG0p40',      dict()),
    ('TRI_DEF_VG0p30',      dict(VG=0.30)),
    ('TRI_DEF_VG0p40_NBG1e16', dict(NBG=1e16)),
    ('TRI_DEF_VG0p40_D10',  dict(DSUB=10.0)),
    ('TRI_DEF_VG0p40_TAU1e-5', dict(TAU=1e-5)),
    ('TRI_IDVG_DP0p20_RC65', dict(IDVG=2, DPHI=0.20, RC=65.0)),
    ('TRI_IDVG_DP0p28_RC65', dict(IDVG=2, DPHI=0.28, RC=65.0)),
    ('TRI_IDVG_DP0p35_RC65', dict(IDVG=2, DPHI=0.35, RC=65.0)),
    ('TRI_IDVG_DP0p28_RC0',  dict(IDVG=2, DPHI=0.28, RC=0.0)),
    ('TRI_IDVG_DP0p00_RC65', dict(IDVG=2, DPHI=0.001, RC=65.0)),   # same electrode form as the DPHI runs, ~no shift (reference)
]
# Calibration stage 2 (2026-10-28): Id-Vd at V_G 0.4 V with the Id-Vg-calibrated gate and series R.
#   Stage 1 result (TRI_IDVG_calib.png): DP0p00_RC65 matches the measured Id-Vg at V_D 0.05 and 1 V; every DPHI > 0 shifts
#   too far. The old 10/12 V_th error came from the electrode form (n.poly contact on top of the poly), not from the WF:
#   calibrated gate = electrode over the whole poly region, WF 4.17 eV (DPHI 0.001 selects that form), 65 Ohm per S/D.
#   In MixedMode the 65 Ohm are circuit resistors (CIRC_R=1), so they do not depend on contact statements after .end.
#   Split: impact Selberherr scale AN / BN (one at a time) and Si lifetime TAU. Targets: calib_targets.dat (VLU1 7.38, VLU2 11.58 V).
CAL = dict(DPHI=0.001, RC=65.0, CIRC_R=1)
CASES += [(n, dict(CAL, **c)) for n, c in [
    ('TRI_IV_CAL',         dict()),
    ('TRI_IV_CAL_BN0p9',   dict(BN=0.9)),
    ('TRI_IV_CAL_BN1p1',   dict(BN=1.1)),
    ('TRI_IV_CAL_BN1p2',   dict(BN=1.2)),
    ('TRI_IV_CAL_AN0p5',   dict(AN=0.5)),
    ('TRI_IV_CAL_AN2',     dict(AN=2.0)),
    ('TRI_IV_CAL_TAU1e-6', dict(TAU=1e-6)),
    ('TRI_IV_CAL_TAU1e-8', dict(TAU=1e-8)),
]]
# ATLAS Selberherr defaults (electrons/holes, low-field branch); AN/BN scale them.
SELB = dict(an1=7.03e5, an2=7.03e5, bn1=1.231e6, bn2=1.231e6, ap1=6.71e5, ap2=1.582e6, bp1=1.693e6, bp2=2.036e6)

def deck(name, p):
    tr = (p['VMAX'] / p['RATE']) * 1e-3
    imp = 'impact selb length.rel'
    if p['AN'] != 1.0 or p['BN'] != 1.0:
        imp += ' an1=%.4g an2=%.4g bn1=%.4g bn2=%.4g ap1=%.4g ap2=%.4g bp1=%.4g bp2=%.4g' % (
            SELB['an1']*p['AN'], SELB['an2']*p['AN'], SELB['bn1']*p['BN'], SELB['bn2']*p['BN'],
            SELB['ap1']*p['AN'], SELB['ap2']*p['AN'], SELB['bp1']*p['BN'], SELB['bp2']*p['BN'])
    models = 'models print bgn consrh %sconmob fldmob fermi trap.tunnel bbt.std temp=300' % ('auger ' if p['AUG'] else '')
    L = [f'# {name} : triristor calibration deck. Params: ' + ', '.join(f'{k}={v}' for k, v in p.items()),
         '# Generated by 1010_calib/make_tri.py. Target device: Noh et al., IEEE EDL 46(8) 1269-1272, 2025.',
         'go atlas simflags="-P 1"',
         'set Lg = 3.0', 'set Lsd = 1.0', 'set tox = 0.02', 'set tgate = 0.25', f'set Dsub = {p["DSUB"]}',
         f'mesh space.mult = 1.0 width = {p["W"]:g}',
         'x.mesh loc=0.00 spac=0.25', 'x.mesh loc=$Lsd-0.25 spac=0.05', 'x.mesh loc=$Lsd spac=0.01', 'x.mesh loc=$Lsd+0.3 spac=0.05',
         'x.mesh loc=$Lsd+$Lg/2 spac=0.25', 'x.mesh loc=$Lsd+$Lg-0.4 spac=0.04', 'x.mesh loc=$Lsd+$Lg-0.1 spac=0.008', 'x.mesh loc=$Lsd+$Lg spac=0.005',
         'x.mesh loc=$Lsd+$Lg+0.15 spac=0.02', 'x.mesh loc=$Lsd+$Lg+$Lsd spac=0.25',
         'y.mesh loc=-$tox-$tgate spac=0.1', 'y.mesh loc=-$tox spac=0.005', 'y.mesh loc=0.00 spac=0.002', 'y.mesh loc=0.03 spac=0.008',
         'y.mesh loc=0.2 spac=0.02', 'y.mesh loc=0.45 spac=0.05', 'y.mesh loc=1.0 spac=0.2', 'y.mesh loc=$Dsub spac=0.8',
         'region num=1 x.min=$Lsd x.max=$Lsd+$Lg y.max=-$tox poly',
         'region num=2 x.min=$Lsd x.max=$Lsd+$Lg y.max=0 y.min=-$tox oxide',
         'region num=3 y.min=0 y.max=$Dsub silicon',
         'region num=4 x.max=$Lsd y.max=0 material=vacuum',
         'region num=5 x.min=$Lsd+$Lg y.max=0 material=vacuum',
         ('electrode name=gate x.min=$Lsd x.max=$Lsd+$Lg y.min=-$tox-$tgate y.max=-$tox-$tgate' if p['DPHI'] == 0 else
          # DPHI != 0: the electrode covers the whole poly region so that its work function (not the n+ poly) sets V_fb
          'electrode name=gate x.min=$Lsd x.max=$Lsd+$Lg y.min=-$tox-$tgate y.max=-$tox'),
         'electrode name=source x.max=$Lsd-0.1 y.min=0 y.max=0',
         'electrode name=drain x.min=$Lsd+$Lg+0.1 y.min=0 y.max=0',
         f'doping uniform conc={p["NBG"]:.3g} p.type reg=3',
         'doping gaussian conc=5e16 p.type peak=0.10 char=0.19 reg=3',
         'doping gaussian conc=7e20 n.type peak=0 char=0.055 x.right=$Lsd lat.char=0.04 reg=3',
         'doping gaussian conc=7e20 n.type peak=0 char=0.055 x.left=$Lsd+$Lg lat.char=0.04 reg=3',
         'doping uniform conc=1e21 n.type reg=1',
         f'save outf={name}_INIT.str',
         ('contact name=gate n.poly' if p['DPHI'] == 0 else 'contact name=gate workfun=%.3f' % (4.17 + p['DPHI'])),
         *(['contact name=source resistance=%.6g' % (p['RC'] * p['W']), 'contact name=drain resistance=%.6g' % (p['RC'] * p['W'])] if p['RC'] > 0 and not p['CIRC_R'] else []),
         'probe name=VB_well potential x=$Lsd+$Lg/2 y=0.12',
         'probe name=VB_deep potential x=$Lsd+$Lg/2 y=1.0',
         'probe name=PH_well P.CONC x=$Lsd+$Lg/2 y=0.12',
         f'material material=silicon taun0={p["TAU"]:.3g} taup0={p["TAU"]:.3g}',
         models, imp,
         'output band.param con.band val.band recomb u.srh u.bbt impact e.field',
         'method newton climit=100 itlimit=200 trap maxtraps=10',
         'solve init', 'solve prev']
    # models must be repeated after .end for the MixedMode device
    phys = (['contact name=gate workfun=%.3f' % (4.17 + p['DPHI'])] if p['DPHI'] != 0 else []) + [
            f'material material=silicon taun0={p["TAU"]:.3g} taup0={p["TAU"]:.3g}', models, imp,
            'output band.param con.band val.band recomb u.srh u.bbt impact e.field',
            'method newton climit=100 itlimit=200 trap maxtraps=10']
    adev = f'Adev 1=drain 0=source 2=gate width={p["W"]:g} infile={name}_INIT.str'
    if p['IDVG'] == 2:   # device-only DC Id-Vg (fast; the device-only form ran cleanly on 10/10)
        L += ['solve vgate=0 vstep=-0.1 vfinal=-1.0 name=gate', 'solve vdrain=0.05', f'log outf={name}_vd0p05_up.log',
              'solve vgate=-1.0 vstep=0.05 vfinal=3.0 name=gate', 'log off', 'solve vgate=-1.0 vstep=-0.2 vfinal=-1.0 name=gate',
              'solve vgate=3.0 vstep=-0.2 vfinal=-1.0 name=gate', 'solve vdrain=0.1 vstep=0.1 vfinal=1.0 name=drain',
              f'log outf={name}_vd1_up.log', 'solve vgate=-1.0 vstep=0.05 vfinal=3.0 name=gate', 'log off', 'quit']
        return '\n'.join(L) + '\n'
    if p['IDVG']:
        # MixedMode .dc cannot jump from zero bias to Vd = 1 V: ramp to each start bias here and start from that .str
        L += ['solve vgate=0 vstep=-0.1 vfinal=-1.0 name=gate', 'solve vdrain=0.05', f'save outf={name}_VD0p05.str master',
              'solve vdrain=0.1 vstep=0.1 vfinal=1.0 name=drain', f'save outf={name}_VD1.str master']
        for vd, tag, st in ((0.05, 'vd0p05_up', 'VD0p05'), (1.0, 'vd1_up', 'VD1')):
            L += ['', 'go atlas simflags="-P 1"', '.begin', f'Vdrain 1 0 {vd}', 'Vgate  2 0 -1.0',
                  adev.replace('_INIT.str', f'_{st}.str'),
                  f'.nodeset v(1)={vd} v(2)=-1.0', '.options print relpot', f'.log outfile={name}_{tag}.log',
                  '.dc Vgate -1.0 3.0 0.05', '.end', ''] + phys
        L += ['', 'go atlas simflags="-P 1"', 'quit']
        return '\n'.join(L) + '\n'
    L += [f'solve vgate=0 vstep=0.05 vfinal={p["VG"]} name=gate', f'save outf={name}_VG.str master']
    up = [x for x in (2, 4, 6, 7, 8, 9, 10, 11, 12) if x < p['VMAX']] + [p['VMAX']]
    dn = [x for x in (12, 11, 10, 9, 8, 7, 6, 4, 2, 0) if x < p['VMAX']]
    ttop = p['VMAX'] / p['RATE'] * 1e-3
    t, v0, tsave = 0.0, 0.0, []
    for v in up + dn:   # snapshots at the old device-only save points
        t += abs(v - v0) / p['RATE'] * 1e-3; tsave.append(t); v0 = v
    adev = adev.replace('_INIT.str', '_VG.str')
    L += ['', 'go atlas simflags="-P 1"', '.begin',
          *([f'Vdrain 4 0 pwl 0, 0, {ttop:.6e}, {p["VMAX"]}, {2*ttop:.6e}, 0', f'Rd 4 1 {p["RC"]:g}', f'Rs 5 0 {p["RC"]:g}',
             f'Vgate  2 0 {p["VG"]}', adev.replace('0=source', '5=source'), f'.nodeset v(1)=0 v(4)=0 v(5)=0 v(2)={p["VG"]}']
            if p['CIRC_R'] else
            [f'Vdrain 1 0 pwl 0, 0, {ttop:.6e}, {p["VMAX"]}, {2*ttop:.6e}, 0', f'Vgate  2 0 {p["VG"]}', adev,
             f'.nodeset v(1)=0 v(2)={p["VG"]}']), '.numeric lte=0.3 toltr=1e-5', '.options print relpot',
          f'.log outfile={name}.log', f'.tran 1e-9 {2*ttop:.6e}',
          f'.save master={name}_T tsave=' + ' '.join(f'{x:.6e}' for x in sorted(tsave)), '.end', ''] + phys
    L += ['', 'go atlas simflags="-P 1"', 'quit']
    return '\n'.join(L) + '\n'

if __name__ == '__main__':
    for name, ch in CASES:
        p = dict(BASE); p.update(ch)
        if os.path.exists(name + '.in'): continue   # never rewrite a deck that already exists (it records what was run)
        open(name + '.in', 'w').write(deck(name, p)); print('wrote', name)
