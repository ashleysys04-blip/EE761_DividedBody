#!/usr/bin/env python3
"""Island-lifetime sweep on the XS60 family: coupled -> decoupled transition in one device family.

Base: 1007_ddsplit/DDS_TE8_XS60.in (island tau 1e-12 s). NOKILL_TE8_XS60 is the same deck without the two island lines
(island tau = Si tau = 1e-8 s). Here only the island/neck lifetime (regions 9, 10) changes: 1e-11, 1e-10, 1e-9, 3e-9 s (3e-9 added after the first results: the change sits between 1e-10 and 1e-8).
Together with DDS_TE8_XS60 (1e-12) and NOKILL_TE8_XS60 (1e-8) this gives five points at fixed geometry.
Existing decks are not rewritten."""
import os
H = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(H, '..', '1007_ddsplit', 'DDS_TE8_XS60.in')
OLD = ('material region=10 taun0=1e-12 taup0=1e-12', 'material region=9 taun0=1e-12 taup0=1e-12')
src = open(BASE).read()
assert all(src.count(o) == 2 for o in OLD), "base deck changed: island lifetime lines not found twice (device + after .end)"
for tag, tau in (('1em11', '1e-11'), ('1em10', '1e-10'), ('1em9', '1e-9'), ('3em9', '3e-9')):
    n = f'ISL_TAU{tag}_XS60'
    fn = os.path.join(H, n + '.in')
    if os.path.exists(fn):
        print('exists, not rewritten:', n); continue
    d = src
    for o in OLD:
        d = d.replace(o, o.replace('1e-12', tau))
    d = d.replace('DDS_TE8_XS60', n)
    hdr = (f'# {n} : island-lifetime sweep, generated by 1029_isltau/make_isltau.py from 1007_ddsplit/DDS_TE8_XS60.in\n'
           f'# Only change: island + neck lifetime (regions 9, 10) 1e-12 -> {tau} s. Everything else identical.\n')
    open(fn, 'w').write(hdr + d); print('wrote', n + '.in')
